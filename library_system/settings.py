# Helper for configuration via python-decouple with graceful fallback
try:
    from decouple import config, Csv
except ImportError:
    def config(key, default='', cast=None):
        val = os.environ.get(key, default)
        if cast is bool:
            return str(val).lower() in ('true', '1', 't', 'yes')
        if cast:
            return cast(val)
        return val

    def Csv():
        return lambda val: [v.strip() for v in val.split(',') if v.strip()] if isinstance(val, str) else (val or [])

